package research.java.sintaxe.loops.fors;

public class forsimples {
    public static void main(String[] args) {
        for (int i = 0; i < 5; i++) {
            // int começa em 0, enquanto i for menor que 5, incrementa i em 1
            System.out.println(i+1); // imprime o valor de i+1, ou seja, de 1 a 5
        }
    }
}
